    async def _collect_analytics(self) -> dict[str, Any]:
        if not self._engine:
            return {}
        ledger = self._engine._ledger
        return {
            "advanced_analytics": await ledger.get_advanced_analytics(),
            "hold_time_stats": await ledger.get_hold_time_stats(),
            "pnl_summary": await ledger.get_pnl_summary(),
            "performance_by_regime": await ledger.get_performance_by_regime(),
            "performance_by_setup": await ledger.get_performance_by_setup(),
            "live_readiness": await ledger.get_live_readiness_score(),
            "decision_analytics": await ledger.get_decision_analytics(),
        }

    def _build_recommendations(
        self,
        adv: dict,
        hold: dict,
        pnl: dict,
        regime: list,
        setup: list,
    ) -> list[str]:
        recs: list[str] = []
        closed = adv.get("closed_count", 0)

        if closed < 10:
            recs.append(f"Only {closed} closed trades. Continue paper trading — analytics not yet significant.")
            return recs

        if adv.get("net_after_gas_usd", 0.0) <= 0:
            recs.append("Net PnL after gas is negative or zero. Do not advance to live mode.")
        if adv.get("win_rate_pct", 0.0) < 45:
            recs.append("Win rate below 45%. Review entry signal quality before live consideration.")
        if adv.get("profit_factor", 0.0) < 1.0:
            recs.append("Profit factor < 1.0 means gross losses exceed gross profits. Strategy is losing money.")
        if pnl.get("max_drawdown", 0.0) * 100 > 10:
            recs.append("Max drawdown > 10%. Add risk brakes before live transition.")
        if hold.get("avg_hold_seconds", 0) < 180:
            recs.append("Very short hold times — gas likely eating all profits. Widen entry/exit bands.")

        best_regimes = [r for r in regime if r.get("expectancy_usd", 0.0) > 0]
        if best_regimes:
            recs.append(f"Positive expectancy observed in: {', '.join(r.get('regime_label','?') for r in best_regimes[:3])}. Focus on these regimes.")

        if not recs:
            recs.append("Strategy metrics look healthy. Continue accumulating data before live transition.")
        return recs

    @staticmethod
    def _fmt_s(seconds: float) -> str:
        s = int(seconds)
        if s < 60:
            return f"{s}s"
        if s < 3600:
            return f"{s // 60}m {s % 60}s"
        return f"{s // 3600}h {(s % 3600) // 60}m"


