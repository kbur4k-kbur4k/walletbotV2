"""
wallet_manager/research_brain.py

Phase 4: Research Brain
=======================
AI-assisted research layer that generates weekly strategy reviews,
trade cluster analysis, threshold tuning suggestions, worst-trade
postmortems, and best-setup summaries — from the paper_decisions and
paper_trades ledger.

Design principles:
- LLM summarises, analyses, compares, suggests experiments, explains failures.
- LLM does NOT directly execute trades or place orders.
- All outputs are text reports stored/returned for operator review.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from typing import Any

from wallet_manager.security.logging_filter import build_logger

log = build_logger(__name__)


# ---------------------------------------------------------------------------
# Data classes
# ---------------------------------------------------------------------------


@dataclass
class ResearchReport:
    """A single research report generated by the brain."""

    report_type: str                    # weekly_review | postmortem | threshold_tuning | cluster
    generated_at: float = field(default_factory=time.time)
    title: str = ""
    sections: list[dict[str, str]] = field(default_factory=list)
    raw_data: dict[str, Any] = field(default_factory=dict)
    recommendations: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "report_type": self.report_type,
            "generated_at": self.generated_at,
            "title": self.title,
            "sections": self.sections,
            "raw_data": self.raw_data,
            "recommendations": self.recommendations,
        }

    def to_text(self) -> str:
        lines = [f"# {self.title}", f"Generated: {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime(self.generated_at))}", ""]
        for section in self.sections:
            lines.append(f"## {section.get('heading', '')}")
            lines.append(section.get("body", ""))
            lines.append("")
        if self.recommendations:
            lines.append("## Recommendations")
            for r in self.recommendations:
                lines.append(f"- {r}")
        return "\n".join(lines)


