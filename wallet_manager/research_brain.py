class ResearchBrain:
    """Generates structured research reports from paper trading ledger data.

    All analysis is rule-based / statistical; no external LLM call is made
    inside this class.  The output is structured data that can be passed to
    an LLM agent (Phase 8) or rendered directly in the dashboard.
    """

    def __init__(self, paper_engine: Any | None = None) -> None:
        self._engine = paper_engine

